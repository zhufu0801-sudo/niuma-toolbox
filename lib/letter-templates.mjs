import {wareki,JIKOU} from './letter-layout.mjs';

export const GREETINGS=[
  {id:'notice',title:'ご案内',titleZh:'通知（ご案内）'},
  {id:'moving',title:'移転のご挨拶',titleZh:'搬迁通知（移転のご挨拶）'},
  {id:'yearend',title:'年末のご挨拶',titleZh:'年末问候（年末のご挨拶）'},
  {id:'thanks',title:'お礼状',titleZh:'感谢信（お礼状）'}
];

export function greetingText(id,date=new Date()){
  const jikou=JIKOU[date.getMonth()],kichi=wareki(date,{kichijitsu:true}),today=wareki(date);
  switch(id){
    case 'notice':return ['拝啓　'+jikou+'の候　皆様におかれましてはますますご清祥のこととお慶び申し上げます。','さて、このたび下記のとおり〇〇を開催する運びとなりました。','ご多用中とは存じますが、ぜひご出席くださいますようご案内申し上げます。','敬具',today,'〇〇株式会社','記','日時　〇月〇日（〇）午後〇時より','場所　〇〇','以上'].join('\n');
    case 'moving':return ['拝啓　'+jikou+'の候　貴社ますますご清栄のこととお慶び申し上げます。','平素は格別のお引き立てを賜り、厚く御礼申し上げます。','さて、このたび弊社は業務拡張に伴い、下記へ事務所を移転することとなりました。','これを機に社員一同、より一層業務に励む所存でございます。','今後とも変わらぬご支援を賜りますよう、お願い申し上げます。','まずは略儀ながら書中をもちましてご挨拶申し上げます。','敬具',kichi,'〇〇株式会社','代表取締役　〇〇　〇〇','記','新住所　〒〇〇〇－〇〇〇〇　〇〇県〇〇市〇〇','電話番号　〇〇－〇〇〇〇－〇〇〇〇','業務開始日　〇月〇日','以上'].join('\n');
    case 'yearend':return ['拝啓　師走の候　貴社ますますご盛栄のこととお慶び申し上げます。','本年も格別のお引き立てを賜り、誠にありがとうございました。','来る年も社員一同、より一層のサービス向上に努めてまいりますので、変わらぬご愛顧のほどお願い申し上げます。','なお、年末年始の休業期間は下記のとおりとさせていただきます。','敬具',wareki(new Date(date.getFullYear(),11,1),{kichijitsu:true}),'〇〇株式会社','記','休業期間　十二月〇日（〇）～一月〇日（〇）','以上'].join('\n');
    case 'thanks':return ['拝啓　'+jikou+'の候　ますますご清祥のこととお慶び申し上げます。','先日はご多忙のところ、格別のご配慮を賜り誠にありがとうございました。','おかげさまで、無事に〇〇を終えることができました。心より御礼申し上げます。','今後ともご指導ご鞭撻のほど、よろしくお願い申し上げます。','まずは略儀ながら書中にて御礼申し上げます。','敬具',today,'〇〇　〇〇','〇〇　〇〇様'].join('\n');
    default:throw Error('没有这个例文。');
  }
}
